import { expect, test } from '@playwright/test'

test('тренер фильтрует команду, смотрит импортированные показатели и меняет предупреждения', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'windows-desktop', 'Интерфейс тренера проверяется на Windows и планшетном размере.')
  await page.goto('/login')
  await page.getByLabel('Электронная почта').fill('profiles-coach@example.com')
  await page.getByLabel('Пароль', { exact: true }).fill(process.env.CTM_E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()

  await page.getByLabel('Поиск по имени').fill('analytics-review')
  await expect(page.getByRole('row', { name: /analytics-review/u })).toBeVisible()
  await expect(page.getByRole('row', { name: /coach-review/u })).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Группа', exact: true }).selectOption('Шоссе')
  await page.getByRole('combobox', { name: 'Сортировка' }).selectOption('tss')
  await page.getByRole('combobox', { name: 'Порядок' }).selectOption('desc')
  const row = page.getByRole('row', { name: /analytics-review/u })
  await expect(row.getByText('TSS · 2,13', { exact: true })).toBeVisible()
  await expect(row.getByText('TSS у 1 из 2')).toBeVisible()
  await row.getByRole('link', { name: 'Журнал', exact: true }).click()
  await expect(page.getByText('Запусков пока нет.')).toBeVisible()

  const tabs = page.getByRole('navigation', { name: 'Вкладки спортсмена' })
  await expect(tabs.getByRole('link')).toHaveCount(7)
  await expect(tabs.getByRole('link', { name: 'Нагрузка и восстановление' })).toBeVisible()
  await tabs.getByRole('link', { name: 'Аналитика', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Недельная нагрузка' })).toBeVisible()
  await page.getByRole('button', { name: 'Свой период' }).click()
  await page.getByLabel('Начало периода').fill('2000-01-01')
  await page.getByLabel('Конец периода').fill('2000-01-03')
  await page.getByRole('button', { name: 'Применить период' }).click()
  await expect(page.getByText('1 января 2000 г. — 3 января 2000 г.')).toBeVisible()
  await expect(page.getByText('Нет данных за выбранный период.').first()).toBeVisible()
  await page.getByRole('button', { name: '90 дней' }).click()
  await page.getByRole('combobox', { name: 'Показатель тренировки' }).selectOption('np')
  await expect(page.getByRole('group', { name: 'NP', exact: true }).locator('.recharts-surface')).toBeVisible()
  await page.getByText('Значения и причины пропусков').click()
  const powered = page.getByRole('row').filter({ has: page.getByRole('cell', { name: '200 Вт', exact: true }) })
  await expect(powered).toHaveCount(1)
  await expect(page.getByRole('cell', { name: 'В FIT нет записей этого датчика.' })).toBeVisible()
  await powered.getByRole('link').click()
  await expect(page.getByRole('heading', { name: 'Показания датчиков' })).toBeVisible()
  for (const name of ['Мощность', 'Пульс', 'Каденс']) {
    await expect(page.getByRole('group', { name, exact: true }).locator('.recharts-surface')).toBeVisible()
  }

  await page.setViewportSize({ width: 1024, height: 768 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('link', { name: 'Команда', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Спортсмены команды' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('link', { name: 'Настроить предупреждения' }).click()
  await page.getByLabel('Усталость от', { exact: true }).fill('5')
  await page.getByRole('button', { name: 'Сохранить настройки' }).click()
  await expect(page.getByText('Изменения сохранены.')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Усталость от', { exact: true })).toHaveValue('5')
})
