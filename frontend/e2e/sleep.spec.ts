import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

const dayLabel = new Intl.DateTimeFormat('ru', { dateStyle: 'long', timeZone: 'UTC' })

function relativeDay(date: string, offset: number) {
  return new Date(Date.parse(date) + offset * 86_400_000).toISOString().slice(0, 10)
}

async function signIn(page: Page, email: string) {
  await page.goto('/login')
  await page.getByLabel('Электронная почта').fill(email)
  await page.getByLabel('Пароль', { exact: true }).fill(process.env.CTM_E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
}

test('сон без Garmin: ввод, исправление, перенос, выбор источника и история', async ({ page }, info) => {
  test.setTimeout(60_000)
  const garminRequests: string[] = []
  page.on('request', request => { if (/garmin/iu.test(request.url())) garminRequests.push(request.url()) })
  await signIn(page, `sleep-${info.project.name}@example.com`)
  await page.getByRole('link', { name: 'Сон и восстановление' }).click()
  await expect(page.getByRole('heading', { name: 'Сон и восстановление' })).toBeVisible()
  const date = page.getByLabel('Дата пробуждения', { exact: true })
  const today = await date.inputValue()
  const form = page.getByRole('form', { name: 'Запись сна' })
  const summary = page.locator('.sleep-summary')
  const graph = page.getByRole('region', { name: 'График сна' })
  const todayRow = graph.getByRole('row').filter({ has: page.getByRole('rowheader', { name: dayLabel.format(new Date(today)), exact: true }) })
  await expect(summary).toContainText('Записи сна нет')
  await form.getByLabel('Время засыпания').fill('23:15')
  await form.getByLabel('Время пробуждения').fill('07:00')
  await expect(form.getByText('По времени: 7 ч 45 мин')).toBeVisible()
  await form.getByLabel('Субъективное качество сна').selectOption('4')
  await form.getByLabel('Самооценка восстановления').selectOption('5')

  let warned = false
  page.once('dialog', async dialog => { warned = true; await dialog.dismiss() })
  await page.getByRole('link', { name: 'Утренняя анкета' }).click()
  await expect.poll(() => warned).toBe(true)
  await expect(form.getByLabel('Время засыпания')).toHaveValue('23:15')

  const block = '**/api/v1/athletes/*/sleep/*/manual'
  await page.route(block, async route => { await route.abort('failed') })
  await form.getByRole('button', { name: 'Сохранить сон' }).click()
  await expect(form.getByRole('alert')).toHaveText('Не удалось связаться с сервером. Повторите попытку.')
  await expect(form.getByLabel('Время пробуждения')).toHaveValue('07:00')
  await page.unroute(block)
  await form.getByRole('button', { name: 'Сохранить сон' }).click()
  await expect(form.getByRole('status')).toHaveText('Изменения сохранены.')
  await expect(summary).toContainText('7 ч 45 мин')
  await expect(summary).toContainText('Не заполнена')
  await graph.getByText('Данные графика · Продолжительность сна', { exact: true }).click()
  await expect(todayRow.getByRole('cell', { name: '465 мин', exact: true })).toBeVisible()
  await expect(todayRow.getByRole('cell', { name: '450 мин', exact: true })).toBeVisible()

  await form.getByLabel('Длительность вручную, мин').fill('400')
  await form.getByRole('button', { name: 'Сохранить сон' }).click()
  await expect(summary).toContainText('6 ч 40 мин')
  await expect(summary).toContainText('Ручная поправка')
  await expect(todayRow.getByRole('cell', { name: '400 мин', exact: true })).toBeVisible()
  await page.getByText('Перенести запись сна', { exact: true }).click()
  const move = page.getByRole('form', { name: 'Перенос сна' })
  const yesterday = relativeDay(today, -1)
  await move.getByLabel('Новая дата пробуждения').fill(yesterday)
  await move.getByRole('button', { name: 'Перенести сон' }).click()
  await expect(move.getByRole('alert')).toContainText('На выбранную дату уже есть запись')
  const target = relativeDay(today, -12)
  await move.getByLabel('Новая дата пробуждения').fill(target)
  await move.getByRole('button', { name: 'Перенести сон' }).click()
  await expect(date).toHaveValue(target)
  await expect(page.getByText(/Сон перенесён на/u)).toBeVisible()
  await expect(form.getByLabel('Время засыпания')).toHaveValue('23:15')
  await expect(form.getByLabel('Длительность вручную, мин')).toHaveValue('400')
  await expect(page.getByRole('region', { name: 'История сна' }).getByRole('button', { name: `Открыть сон за ${dayLabel.format(new Date(target))}` })).toBeVisible()
  await page.getByRole('link', { name: 'Утренняя анкета' }).press('Enter')
  const diary = page.getByRole('form', { name: 'Утренняя анкета' })
  await expect(diary.getByRole('group', { name: 'Качество сна' }).getByRole('radio', { name: '4', exact: true })).toBeChecked()
  await expect(diary.getByLabel('Самооценка восстановления (необязательно)')).toHaveValue('5')
  await page.getByRole('link', { name: 'Сон и восстановление' }).click()

  await date.fill(yesterday)
  await expect(summary).toContainText('Историческая запись')
  await form.getByLabel('Длительность вручную, мин').fill('390')
  await form.getByRole('button', { name: 'Сохранить сон' }).click()
  const conflict = page.getByRole('group', { name: 'Значение для аналитики' })
  await expect(conflict.getByRole('button', { name: /Введено вручную/u })).toHaveAttribute('aria-pressed', 'true')
  await conflict.getByRole('button', { name: /Историческая запись/u }).click()
  await expect(conflict.getByRole('button', { name: /Историческая запись/u })).toHaveAttribute('aria-pressed', 'true')
  await expect(summary).toContainText('7 ч')
  await conflict.getByRole('button', { name: 'Вернуть выбор по умолчанию' }).click()
  await expect(conflict.getByRole('button', { name: /Введено вручную/u })).toHaveAttribute('aria-pressed', 'true')

  await graph.getByText('Данные графика · Продолжительность сна', { exact: true }).click()
  await expect(graph.getByRole('row').filter({ hasText: 'Указано отсутствие сна' })).toHaveCount(1)
  await expect(graph.getByText('Записи сна нет').first()).toBeVisible()
  await expect(graph.getByText(/Индивидуальная норма рассчитана по предыдущим 28 дням/u)).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(garminRequests).toEqual([])
})

test('тренер читает сон и норму в карточке без доступа к редактированию и Garmin', async ({ page }) => {
  await signIn(page, 'sleep-coach@example.com')
  await page.getByRole('link', { name: 'Сон coach-review', exact: true }).click()
  const sleep = page.getByRole('region', { name: 'Сон и восстановление спортсмена' })
  await expect(sleep).toBeVisible()
  const date = sleep.getByLabel('Дата сна')
  await expect(sleep).toContainText('Записи сна нет')
  await date.fill(relativeDay(await date.inputValue(), -1))
  await expect(sleep).toContainText('Историческая запись')
  await expect(sleep).toContainText('450 мин')
  await expect(sleep).toContainText('Отклонение')
  await expect(sleep.getByText('Заполнена', { exact: true })).toBeVisible()
  await expect(sleep.getByRole('heading', { name: 'Предупреждения восстановления' })).toBeVisible()
  await expect(sleep.getByText('Недостаточность данных', { exact: true })).toBeVisible()
  await expect(sleep.getByRole('button', { name: /Сохранить|Garmin/u })).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Импорт отчёта о сне' })).toHaveCount(0)
  await page.goto('/diary/sleep')
  await expect(page.getByRole('heading', { name: 'Доступ ограничен' })).toBeVisible()
})

test('личный отчёт о сне: проверка файла, подтверждение, повтор и история', async ({ page }, info) => {
  await signIn(page, `sleep-${info.project.name}@example.com`)
  await page.getByRole('link', { name: 'Сон и восстановление' }).click()
  const section = page.getByRole('region', { name: 'Импорт отчёта о сне' })
  const history = section.getByRole('region', { name: 'Загруженные ночи' })
  const input = section.getByLabel('Отчёт JSON')
  const preview = section.getByRole('button', { name: 'Проверить файл' })
  const save = section.getByRole('button', { name: 'Сохранить отчёт' })
  const select = (content: string) => input.setInputFiles({ name: 'report.json', mimeType: 'application/json', buffer: Buffer.from(content) })
  const report = JSON.stringify({ schema_version: 1, sleep: [{ sleep_date: '2026-11-22', duration_minutes: 473, rem_minutes: 68 }] })

  await select('not JSON')
  await preview.click()
  await expect(section.getByRole('alert')).toContainText('Проверьте JSON-файл')
  await select(report)
  await preview.click()
  await expect(section.getByRole('heading', { name: 'Предпросмотр отчёта' })).toBeVisible()
  await expect(section.getByText('7 ч 53 мин')).toBeVisible()
  await expect(history.getByText('Отчётов пока нет.')).toBeVisible()

  const saveRoute = '**/api/v1/athletes/*/sleep-reports'
  await page.route(saveRoute, route => route.abort('failed'))
  await save.click()
  await expect(section.getByRole('alert')).toHaveText('Не удалось связаться с сервером. Повторите попытку.')
  await expect(section.getByRole('heading', { name: 'Предпросмотр отчёта' })).toBeVisible()
  await page.unroute(saveRoute)
  await save.click()
  await expect(section.getByRole('status')).toHaveText('Ночей сохранено — 1. Без изменений — 0.')
  await expect(history.getByText('68 мин')).toBeVisible()

  await page.reload()
  await expect(history.getByText('7 ч 53 мин')).toBeVisible()
  await select(report)
  await preview.click()
  await save.click()
  await expect(section.getByRole('status')).toHaveText('Ночей сохранено — 0. Без изменений — 1.')
  await expect(history.getByText('7 ч 53 мин')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
