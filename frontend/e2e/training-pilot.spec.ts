import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function signIn(page: Page, email: string) {
  await page.goto('/login')
  await page.getByLabel('Электронная почта').fill(email)
  await page.getByLabel('Пароль', { exact: true }).fill(process.env.CTM_E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
}

async function expectFits(page: Page) {
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
}

test('G5 тренер проходит от команды и причин предупреждения к FIT и базе контрольных попыток', async ({ page }, testInfo) => {
  if (testInfo.project.name !== 'windows-desktop') await page.setViewportSize({ width: 320, height: 720 })
  await signIn(page, 'pilot-coach1@example.com')
  await page.getByRole('link', { name: 'Нагрузка и восстановление', exact: true }).click()
  const squad = page.locator('ul.training-team')
  await expect(squad.getByRole('listitem')).toHaveCount(20)
  await expect(squad.getByRole('listitem').first()).toContainText('04 · heavy-streak')
  await expectFits(page)

  await squad.getByRole('link', { name: '07 · growth-declined' }).click()
  const tabs = page.getByRole('navigation', { name: 'Вкладки нагрузки и восстановления' })
  await tabs.getByRole('link', { name: 'Взаимосвязи', exact: true }).click()
  const warning = page.locator('details.training-warning').filter({ has: page.locator('summary', { hasText: 'Возможное снижение работоспособности' }) })
  await warning.locator('summary').first().click()
  await expect(warning.getByText('Индивидуальная база').first()).toBeVisible()
  await expect(warning.getByText('Попыток в базе: 3 · новых: 2')).toBeVisible()
  await expect(warning.getByText('Это наблюдение по записанным данным. Оно не устанавливает причинную связь.')).toBeVisible()
  await expectFits(page)

  await tabs.getByRole('link', { name: 'Нагрузка', exact: true }).click()
  await page.getByRole('button', { name: '42 дня' }).click()
  await expect(page.getByRole('group', { name: 'ATL', exact: true }).locator('.recharts-surface')).toBeVisible()
  await page.getByText('Данные графика · CTL').click()
  await expect(page.getByRole('region', { name: 'Таблица · CTL' })).toBeVisible()
  await tabs.getByRole('link', { name: 'Восстановление', exact: true }).click()
  await expect(page.getByRole('group', { name: 'Продолжительность сна' }).getByRole('application')).toBeVisible()
  await tabs.getByRole('link', { name: 'Взаимосвязи', exact: true }).click()
  await warning.locator('summary').first().click()
  const decline = warning.getByRole('row').filter({ has: page.getByRole('cell', { name: /-20 Вт.*-10 %/u }) })
  await decline.getByRole('link', { name: /Тренировка \d+/u }).click()
  await expect(page.getByRole('heading', { name: 'Контрольный отрезок' })).toBeVisible()
  await expect(page.getByText('Средняя мощность: 180 Вт', { exact: true })).toBeVisible()
  await expectFits(page)
  await page.getByRole('link', { name: 'К истории сопоставимых попыток' }).click()
  const comparison = page.getByRole('heading', { name: 'Повторное снижение мощности' })
  await expect(comparison).toBeVisible()
  await page.getByText('Исходные попытки общей базы').click()
  await expect(page.getByText(/общая база 200 Вт/u)).toBeVisible()
  await expectFits(page)
})

test('G5 спортсмен видит отсутствие дневника и обновлённую динамику после сохранения', async ({ context, page }, testInfo) => {
  await signIn(page, 'missing-diary@example.com')
  const own = page.getByRole('link', { name: 'Моя нагрузка и восстановление' })
  await own.click()
  await expect(page.getByRole('heading', { name: 'Моя нагрузка и восстановление' })).toBeVisible()
  await expect(page.getByText('Записанная нагрузка')).toBeVisible()
  const missing = page.getByRole('link', { name: /^Заполнить за/u })
  const initial = await missing.count()
  const selected = testInfo.project.name === 'windows-desktop' ? 0 : testInfo.project.name === 'android-viewport' ? 1 : 2
  expect(initial).toBeGreaterThan(selected)
  // Each viewport writes a different date even though the synthetic athlete is shared.
  const link = missing.nth(selected)
  const target = await link.getAttribute('href')
  const selectedName = await link.textContent()
  await link.click()
  await expect(page).toHaveURL(url => url.pathname + url.search === target)
  const form = page.getByRole('form', { name: 'Утренняя анкета' })
  for (const field of ['Качество сна', 'Общая усталость', 'Усталость ног', 'Мотивация', 'Настроение', 'Мышечная болезненность']) {
    await form.getByRole('group', { name: field }).getByRole('radio', { name: '3', exact: true }).check()
  }
  await form.getByRole('radio', { name: 'Нет', exact: true }).check()
  await form.getByLabel(/Продолжительность сна/u).fill('432')
  await form.getByLabel(/Самооценка восстановления/u).selectOption('4')
  await form.getByLabel(/Подтверждение записей/u).selectOption('all_workouts_recorded')
  const save = form.getByRole('button', { name: 'Сохранить дневник' })
  await context.setOffline(true)
  await save.click()
  await expect(form.getByRole('alert')).toContainText('Не удалось связаться с сервером')
  await expect(form.getByLabel(/Продолжительность сна/u)).toHaveValue('432')
  await context.setOffline(false)
  await expect(form.getByRole('alert')).toBeVisible()
  await save.click()
  await expect(form.getByText('Изменения сохранены.')).toBeVisible()
  await own.click()
  await expect(missing).toHaveCount(initial - 1)
  await expect(page.getByRole('link', { name: selectedName!, exact: true })).toHaveCount(0)
  await page.getByText('Данные графика · Продолжительность сна').click()
  await expect(page.getByRole('cell', { name: '432 мин', exact: true }).first()).toBeVisible()
  await expectFits(page)
  await page.goto('/training-intelligence')
  await expect(page.getByRole('heading', { name: 'Доступ ограничен' })).toBeVisible()
})

test('G5 локальные данные доступны без внешних запросов, ошибка связи видна при отключении сети', async ({ context, page }) => {
  await context.route(url => ['http:', 'https:'].includes(url.protocol) && url.hostname !== '127.0.0.1', route => route.abort())
  await signIn(page, 'pilot-coach2@example.com')
  const nav = page.getByRole('navigation', { name: 'Разделы' })
  await nav.getByRole('link', { name: 'Нагрузка и восстановление' }).click()
  await expect(page.locator('ul.training-team').getByRole('listitem')).toHaveCount(20)
  await context.setOffline(true)
  await page.getByRole('link', { name: '01 · high-stable', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Не удалось связаться с сервером')
  await expect(page.getByRole('button', { name: 'Повторить', exact: true })).toBeVisible()
  await context.setOffline(false)
  await expect(page.getByRole('heading', { name: 'Дневной TSS' })).toBeVisible()
})
